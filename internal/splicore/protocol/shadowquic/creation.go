package shadowquic

import (
	"encoding/json"

	"github.com/ike-sh/Splicore/internal/splicore/credential"
	"github.com/ike-sh/Splicore/internal/splicore/domain/access"
	"github.com/ike-sh/Splicore/internal/splicore/domain/secret"
	"github.com/ike-sh/Splicore/internal/splicore/ports"
	"github.com/ike-sh/Splicore/internal/splicore/protocol/creation"
)

func (Module) DecodeCreation(b json.RawMessage) (ports.CreationDraft, error) {
	var w struct {
		Schema     int             `json:"schema"`
		Name       string          `json:"name"`
		Listener   access.Endpoint `json:"listener"`
		Display    access.Endpoint `json:"display_endpoint"`
		Settings   json.RawMessage `json:"settings"`
		PolicyMode string          `json:"policy_mode,omitempty"`
		Users      []struct {
			Name           string             `json:"account_name"`
			Username       string             `json:"username,omitempty"`
			Password       json.RawMessage    `json:"password"`
			Enabled        creation.Flag      `json:"enabled,omitempty"`
			AccountEnabled creation.Flag      `json:"account_enabled,omitempty"`
			Policy         *ports.PolicyDraft `json:"traffic_policy,omitempty"`
		} `json:"users"`
	}
	var draft ports.CreationDraft
	if creation.Decode(b, &w) != nil || creation.ValidateEnvelope(w.Schema, w.Name, w.Listener, w.Display, w.PolicyMode, len(w.Users)) != nil {
		return draft, creation.Invalid()
	}
	s, err := Decode(w.Settings)
	if err != nil {
		return draft, err
	}
	raw, _ := json.Marshal(s)
	draft = ports.CreationDraft{Name: w.Name, Protocol: Key(), Transport: "udp", Listener: w.Listener, Display: w.Display, Settings: raw, TLSVerification: true}
	names, users := map[string]bool{}, map[string]bool{}
	for _, u := range w.Users {
		pass, err := creation.RawField(u.Password)
		if err != nil || u.Username != "" && users[u.Username] {
			return draft, invalid()
		}
		if err = creation.ValidateUser(u.Name, u.Policy, w.PolicyMode, names); err != nil {
			return draft, err
		}
		payload := access.UsernamePasswordPayload{Username: secret.New(u.Username), Password: secret.New(pass)}
		// Missing secrets are generated by the shared creation service, after preview.
		if u.Username != "" {
			check := payload
			if check.Password.Empty() {
				check.Password = secret.New("validation-placeholder")
			}
			if _, err := Pair(check); err != nil {
				return draft, err
			}
		}
		if u.Username != "" {
			users[u.Username] = true
		}
		draft.Users = append(draft.Users, ports.CreationUser{Name: u.Name, Enabled: creation.Enabled(u.Enabled), AccountEnabled: creation.Enabled(u.AccountEnabled), Payload: payload, Policy: u.Policy})
	}
	return draft, nil
}

func (Module) GenerateCreationCredential(payload access.Payload) (access.Payload, error) {
	p, ok := payload.(access.UsernamePasswordPayload)
	if !ok {
		return nil, invalid()
	}
	var err error
	if p.Username.Empty() {
		p.Username, err = credential.GeneratePassword()
		if err != nil {
			return nil, err
		}
	}
	if p.Password.Empty() {
		p.Password, err = credential.GeneratePassword()
		if err != nil {
			return nil, err
		}
	}
	if _, err = Pair(p); err != nil {
		return nil, err
	}
	return p, nil
}
